let currentLanguage = 'en';

function getStoredLanguage() {
    if (typeof Storage !== 'undefined' && localStorage.getItem('quasarapp_language')) {
        const stored = localStorage.getItem('quasarapp_language');
        const validLangs = ['en', 'ru', 'de', 'es'];
        return validLangs.includes(stored) ? stored : null;
    }
    return null;
}

function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('quasarapp_language', lang);
}

function getBrowserLanguage() {
    if (navigator.languages && navigator.languages.length) {
        return navigator.languages[0];
    }
    if (navigator.language) {
        return navigator.language;
    }
    return null;
}

function getLanguageFromBrowserCode(browserLang) {
    if (!browserLang) return 'en';
    const langMap = {
        'ru-RU': 'ru',
        'ru': 'ru',
        'de-DE': 'de',
        'de': 'de',
        'es-ES': 'es',
        'es': 'es',
        'en-US': 'en',
        'en-GB': 'en',
        'en': 'en'
    };
    return langMap[browserLang] || 'en';
}

function toggleLanguage() {
    const languages = ['en', 'ru', 'de', 'es'];
    const currentIndex = languages.indexOf(currentLanguage);
    const nextLang = languages[(currentIndex + 1) % languages.length];
    setLanguage(nextLang);
    updateTranslations();
    updateLanguageButton();
}

function updateLanguageButton() {
    const langBtn = document.querySelector('.lang-btn');
    if (langBtn) {
        langBtn.innerHTML = '<i class="fas fa-globe"></i> ' + currentLanguage.toUpperCase();
        const ariaLabel = translations[currentLanguage]?.aria?.toggleLanguage || 'Toggle language';
        langBtn.setAttribute('aria-label', ariaLabel);
    }
}

function updateTranslations() {
    const elements = document.querySelectorAll('[data-lang]');
    elements.forEach(element => {
        const lang = element.getAttribute('data-lang');
        const keys = lang.split('.');
        let value = translations[currentLanguage];
        
        for (const key of keys) {
            value = value ? value[key] : null;
            if (!value) break;
        }
        
        if (value) {
            if (element.hasAttribute('aria-label')) {
                // For aria-label elements with icons, use innerHTML
                const icon = element.innerHTML.match(/<i[^>]*>.*<\/i>/s);
                if (icon) {
                    element.innerHTML = icon[0] + ' ' + value;
                } else {
                    element.textContent = value;
                }
            } else {
                element.textContent = value;
            }
        }
    });
    
    // Update HTML lang attribute
    const html = document.documentElement;
    html.setAttribute('lang', currentLanguage);
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
    // Check for stored language preference
    let initialLang = getStoredLanguage();
    
    // If no stored preference, use browser language
    if (!initialLang) {
        const browserLang = getBrowserLanguage();
        if (browserLang) {
            const detectedLang = getLanguageFromBrowserCode(browserLang);
            initialLang = detectedLang;
        }
    }
    
    if (initialLang) {
        setLanguage(initialLang);
    } else {
        setLanguage('en');
    }
    
    updateLanguageButton();
    updateTranslations();
    
    // Smooth scrolling for navigation
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
    
    // Add parallax effect to cards
    if (window.ParallaxHandler) {
        window.ParallaxHandler.init();
    }
});
